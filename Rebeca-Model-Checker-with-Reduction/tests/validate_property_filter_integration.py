#!/usr/bin/env python3
"""Actual opt-in production generator: native properties, refusal, deadlock and default compatibility."""
import argparse,json,re,shutil,subprocess,os
from pathlib import Path
import xml.etree.ElementTree as ET
from run_quiescence_models import ROOT,command
from benchmark_scaling import copy_without_por
from experiment_online_property_filter import native_run
from audit_online_property_filter import audit
from compare_model_suite import digest

def main():
 p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);a=p.parse_args();out=a.output.resolve();out.mkdir(parents=True,exist_ok=False);jar=ROOT/'target/rmc-2.14.jar';source=ROOT/'tests/fixtures/CellRegisterObserved.rebeca';badprop=source.with_suffix('.property');goodprop=ROOT/'tests/fixtures/CellRegisterObservedBounds.property'
 changed=out/'changed.rebeca';changed.write_text(source.read_text()+'\n// same behavior, unreviewed source digest\n')
 terminating=out/'terminating.rebeca';terminating.write_text(source.read_text().replace('self.keepAlive();',''))
 unsupported=out/'unsupported.property';unsupported.write_text(badprop.read_text().replace('cell.value == 1','cell.value + 1 == 2'))
 assertion=out/'source_assertion.rebeca';assertion.write_text(source.read_text().replace('value >= 0 && value <= 2','value == 0'))
 cases=[('NoEarlyStore',source,badprop,'assertion failed',True),('StoredBounds',source,goodprop,'satisfied',True),('unreviewed_source',changed,badprop,'assertion failed',False),('unreviewed_healthy',changed,goodprop,'satisfied',False),('unsupported_property',source,unsupported,'assertion failed',False),('terminating',terminating,goodprop,'deadlock',False),('source_assertion',assertion,goodprop,'assertion failed',False)]
 result={'production_opt_in':True,'default_changed':False,'rmc_jar_sha256':digest(jar),'cases':{}}
 for name,model,prop,expected,permission in cases:
  case=out/name;case.mkdir();filtered=case/'filtered';filtered.mkdir()
  command(['java','-jar',jar,'-s',model,'-p',prop,'--aria','--aria-property-filter','-e','TIMED_REBECA','-v','2.3','-o',filtered],ROOT,case/'generate.log')
  text=(filtered/'TimedModelChecker.cpp').read_text();table=re.search(r'static const bool propertyInvisible\[[^;]+;',text)
  if not table or ('true' in table[0])!=permission:raise ValueError(('Wrong permissions',name,table[0] if table else 'missing'))
  control=case/'control';control.mkdir();copy_without_por(filtered,control);rows={}
  for mode in ('control','filtered'):
   rows[mode]=native_run(case/mode)
   if rows[mode]['result']!=expected:raise ValueError((name,mode,'Wrong native outcome',rows[mode]))
   if expected!='satisfied' and rows[mode]['trace_states']<1:raise ValueError('Missing real counterexample')
   if name in ('NoEarlyStore','unreviewed_source','unsupported_property') and rows[mode]['message']!='NoEarlyStore':raise ValueError('Wrong assertion failure')
   print(name,mode,rows[mode]['result'],rows[mode]['states'],rows[mode]['transitions'],flush=True)
  result['cases'][name]={'source_sha256':digest(model),'property_sha256':digest(prop),'partial_permission_present':permission,'modes':rows}
  if name in ('NoEarlyStore','StoredBounds'):
   original=case/'original';original.mkdir();command(['java','-jar',jar,'-s',model,'-p',prop,'--aria','-e','TIMED_REBECA','-v','2.3','-o',original],ROOT,case/'original-generate.log')
   previous=ROOT/'tmp/CellOnlinePropertyFilter'/('CellRegisterObserved' if name=='NoEarlyStore' else 'CellRegisterObservedBounds')/'original'
   if previous.exists():
    differences=[f.name for f in original.iterdir() if f.suffix in ('.cpp','.h') and f.read_bytes()!=(previous/f.name).read_bytes()]
    if differences:raise ValueError(('Default generated bytes changed',differences))
    result['cases'][name]['default_all_generated_files_byte_identical_to_preintegration']=True
  (out/'summary.json').write_text(json.dumps(result,indent=2)+'\n')
 # Compile a fresh diagnostic adapter; no dependency on any previous experiment output.
 classes=out/'metadata-classes';classes.mkdir()
 command(['javac','-cp',jar,'-d',classes,ROOT/'tests/PropertyEffectAstAudit.java'],ROOT,out/'compile-metadata.log')
 healthy=out/'StoredBounds'
 command(['java','-cp',str(jar)+os.pathsep+str(classes),'PropertyEffectAstAudit',source,goodprop,healthy/'metadata.json'],ROOT,out/'metadata.log')
 healthy_experiment=healthy/'experimental';shutil.copytree(healthy/'filtered',healthy_experiment)
 # audit modes include the legacy generated current policy and an explicit refused full control.
 from experiment_online_property_filter import native_run as compile_native
 compile_native(healthy/'original')
 shutil.copytree(out/'unreviewed_healthy/filtered',healthy/'refused_metadata')
 result['healthy_graph_audit']=audit(healthy)
 for name,extra in [('missing_aria',[]),('missing_property',['--aria']),('symmetry',['--aria','--symm'])]:
  d=out/('invalid_'+name);args=['java','-jar',jar,'-s',source,'-e','TIMED_REBECA','-v','2.3','--aria-property-filter','-o',d,*extra]
  if name!='missing_property':args+=['-p',goodprop]
  with (out/(name+'.log')).open('w') as log: rejected = subprocess.run([str(x) for x in args],cwd=ROOT,stdout=log,stderr=log)
  if rejected.returncode == 0 or (d/'TimedModelChecker.cpp').exists() or '--aria-property-filter requires' not in (out/(name+'.log')).read_text():raise ValueError('Invalid mode was not explicitly rejected')
 annotated=out/'annotated.rebeca';annotated.write_text(source.read_text().replace('Cell    cell():();','@priority(2)\n Cell    cell():();'))
 d=out/'invalid_annotated'
 with (out/'annotated.log').open('w') as log:
  refused=subprocess.run(['java','-jar',str(jar),'-s',str(annotated),'-p',str(goodprop),'--aria','--aria-property-filter','-e','TIMED_REBECA','-v','2.3','-o',str(d)],cwd=ROOT,stdout=log,stderr=log)
 if refused.returncode==0 or (d/'TimedModelChecker.cpp').exists() or 'requires an unannotated model' not in (out/'annotated.log').read_text():raise ValueError('Prioritized model not explicitly rejected')
 result['annotated_input_rejected_with_nonzero_exit']=True
 result['invalid_modes_rejected']=True;result['all_passed']=True;(out/'summary.json').write_text(json.dumps(result,indent=2)+'\n');print('PASS: production opt-in native matrix, default bytes, healthy semantics and invalid modes')
if __name__=='__main__':main()
