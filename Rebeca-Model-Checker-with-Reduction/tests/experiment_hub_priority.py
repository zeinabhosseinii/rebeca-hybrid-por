#!/usr/bin/env python3
"""Separate Hub method priorities from actor preference; finite diagnostics only."""
import hashlib,json,re
from pathlib import Path
from experiment_representative_policy import prepare
from run_cycle_barriers import ROOT,compile_run
from audit_online_por import run as semantic_audit
from audit_hub_alternatives import export,avoidance,A,B
from action_por_reference import read_full_graph

OUT=ROOT/'tmp/HubPriority'

def hub_choices(graph,full_sigs,directory):
    states,sigs,edges=export(directory)
    inverse={sig:s for s,sig in full_sigs.items()}
    rows=[]
    closed=set();completed=set();prefix={}
    for line in (directory/'errors.log').read_text().splitlines() if (directory/'errors.log').exists() else []:
        fields=dict(item.split('=',1) for item in line.split()[1:] if '=' in item)
        if line.startswith('POR_STATE '):
            sid=fields['state']+'_0';closed.add(inverse[sigs[sid]])
            prefix[sid]=(set(closed),set(completed))
        elif line.startswith('POR_FULL_BARRIER '):
            completed.add(inverse[sigs[fields['state']+'_0']])
    for s in states:
        fid=inverse.get(sigs[s])
        if fid is None:raise ValueError('Unmatched full state')
        if A not in graph.edges[fid] or B not in graph.edges[fid]:continue
        blocked={}
        if s in prefix:
            seen,barriers=prefix[s]
            blocked={a[1]:sorted(graph.edges[fid][a] & (seen-barriers)) for a in (A,B)}
        rows.append({'hypothetical_single_action_closed_blockers':blocked,'state':s,'full_state':fid,'selected_actions':sorted(edges.get(s,{})),
                     'choices':{a[1]:{'certified':graph.certify(fid,a)[0],
                                     'evidence':graph.certify(fid,a)[1],
                                     'avoidance':avoidance(graph,fid,a)} for a in (A,B)}})
    return rows

def main():
    base=ROOT/'tmp/CycleBarriers/LoadBalancerSmall';full=base/'full'
    model=ROOT.parent/'ARIA/benchmarks/LoadBalancerSmall.rebeca'
    if hashlib.sha256(model.read_bytes()).hexdigest()!='fbd2dbefff81ef86df52c961ba93784f8f5f3ff4bea7a2e9cf9c842ae579108b':
        raise ValueError('Unreviewed sender projection')
    graph=read_full_graph(full/'statespace.xml',full/'report.xml')
    _,fs,_=export(full)
    from audit_both_reductions import audit as graph_audit
    results={'finite_model_only':True,'runtime_generator_changed':False,'full_hub_choices':[],'controls':{}}
    for fid in graph.edges:
        if A in graph.edges[fid] and B in graph.edges[fid]:
            choices={}
            for action,other in ((A,B),(B,A)):
                ok,evidence=graph.certify(fid,action)
                left=set().union(*(graph.edges[t].get(other,set()) for t in graph.edges[fid][action]))
                right=set().union(*(graph.edges[t].get(action,set()) for t in graph.edges[fid][other]))
                choices[action[1]]={'certified':ok,'evidence':evidence,'diamond':bool(left) and left==right,
                                     'avoidance':avoidance(graph,fid,action)}
            results['full_hub_choices'].append({'full_state':fid,'choices':choices})
    for name,policy,priority in [('original','original',False),('hub_priority_only','original',True),
                                  ('actor_preference','static_actor_preference',False),
                                  ('actor_and_hub_priority','static_actor_preference',True)]:
        d=OUT/name;order=prepare(base/'aria_ast',d,policy)
        if priority:
            p=d/'LoadBalancerHubActor.cpp';text=p.read_text()
            for message in (1,2):
                text,count=re.subn(rf'messagePriorities\[{message}\] = [^;]+;',
                                    f'messagePriorities[{message}] = {message};',text)
                if count!=1:raise ValueError('Expected one priority assignment')
            p.write_text(text)
        report=compile_run(d,['-DPOR_DIAGNOSTICS','-DEXPORT_STATE_SPACE'])
        if report['result']!='satisfied':raise ValueError(report)
        finite=graph_audit(full,d)
        try:
            semantic_audit(full,d,model,d/'semantic.json')
            online={'status':'passed'}
        except ValueError as error:
            if name!='actor_and_hub_priority':raise
            online={'status':'not_certified','reason':str(error)}
        results['controls'][name]={**report,'order':order,'finite_graph_audit':finite,'online_scope_audit':online,
                                  'hub_choices':hub_choices(graph,fs,d)}
        print(name,report,'mixed Hub states',len(results['controls'][name]['hub_choices']),flush=True)
    # Static control is generated by compare_representatives.sh with this RMC.
    static=ROOT/'tmp/RepresentativeChoices/static'
    from audit_both_reductions import audit
    results['static']={'audit':audit(full,static),'hub_choices':hub_choices(graph,fs,static)}
    (OUT/'summary.json').write_text(json.dumps(results,indent=2)+'\n')
    print('PASS: finite graph checks; online scope limitations reported separately, not certified')

if __name__=='__main__':main()
